"""Encode the actual README screen recording and its short GitHub preview.

No UI, model reply, or execution result is generated by this renderer. The
capture script must finish successfully before any recording is published.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/assets/readme"


def run(args: list[str]) -> str:
    result = subprocess.run(args, check=True, capture_output=True, text=True)
    return result.stdout + result.stderr


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capture-dir", type=Path, default=ROOT / ".deermate/readme-media")
    parser.add_argument("--ffmpeg", help="Defaults to system FFmpeg or imageio-ffmpeg")
    args = parser.parse_args()
    ffmpeg = args.ffmpeg or shutil.which("ffmpeg")
    if not ffmpeg:
        import imageio_ffmpeg

        ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
    capture = json.loads((args.capture_dir / "capture.json").read_text())
    assert capture["passed"] and capture["synthetic_account"]
    assert capture["synthetic_demo_account_disabled_after_capture"]
    assert capture["model_submissions"] == 0 and capture["page_errors"] == []
    source = args.capture_dir / "capture.webm"
    assert source.is_file()
    video = OUT / "workspace-tour.mp4"
    # H.264/yuv420p + front-loaded metadata for ordinary browser playback.
    run(
        [
            ffmpeg,
            "-y",
            "-ss",
            str(capture["chapters"][0]["seconds"] + 0.25),
            "-i",
            str(source),
            "-an",
            "-map_metadata",
            "-1",
            "-vf",
            "fps=24,scale=1280:-2:flags=lanczos,format=yuv420p",
            "-c:v",
            "libx264",
            "-preset",
            "medium",
            "-crf",
            "22",
            "-movflags",
            "+faststart",
            "-metadata",
            "title=DeerMate workspace walkthrough",
            "-metadata",
            "comment=Actual local UI; sample data; no model or Native execution",
            str(video),
        ]
    )
    # An excerpt of the real memory-editing scene; never a synthetic animation.
    begin = capture["chapters"][1]["seconds"]
    gif = OUT / "workspace-preview.gif"
    run(
        [
            ffmpeg,
            "-y",
            "-ss",
            str(begin),
            "-t",
            "7",
            "-i",
            str(source),
            "-filter_complex",
            "fps=8,scale=960:-2:flags=lanczos,split[a][b];"
            "[a]palettegen=max_colors=96:stats_mode=diff[p];"
            "[b][p]paletteuse=dither=bayer:bayer_scale=3",
            "-loop",
            "0",
            str(gif),
        ]
    )
    decoded = run([ffmpeg, "-v", "error", "-i", str(video), "-f", "null", "-"])
    assert not decoded.strip(), "MP4 decoding errors"
    run([ffmpeg, "-v", "error", "-i", str(gif), "-f", "null", "-"])
    assert video.stat().st_size < 8_000_000 and gif.stat().st_size < 2_000_000
    files = ["workspace.png", "memory-mobile.png", "workspace-preview.gif", "workspace-tour.mp4"]
    receipt = {
        "passed": True,
        "source_base": subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip(),
        "capture_date": datetime.fromtimestamp(source.stat().st_mtime, UTC).date().isoformat(),
        "source": "Running local Workspace v2 production build",
        "sample_data": True,
        "actual_ui_and_persisted_memory_correction": True,
        "empty_temporary_chat_created": True,
        "model_submissions": 0,
        "native_tasks": 0,
        "page_errors": [],
        "synthetic_demo_account_disabled_after_capture": True,
        "video": {
            "codec": "H.264",
            "pixel_format": "yuv420p",
            "width": 1280,
            "fps": 24,
            "audio": False,
            "decoded_without_errors": True,
        },
        "gif": {"width": 960, "fps": 8, "seconds": 7, "decoded_without_errors": True},
        "files": {
            name: {
                "bytes": (OUT / name).stat().st_size,
                "sha256": hashlib.sha256((OUT / name).read_bytes()).hexdigest(),
            }
            for name in files
        },
        "scope": capture["scope"],
    }
    (ROOT / "docs/verification/readme-media-2026-11-10.json").write_text(
        json.dumps(receipt, indent=2) + "\n"
    )
    print(
        json.dumps(
            {"passed": True, "mp4_bytes": video.stat().st_size, "gif_bytes": gif.stat().st_size}
        )
    )


if __name__ == "__main__":
    main()
